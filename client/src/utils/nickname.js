/** 추천 닉네임으로 쓰지 않는 말 (지속 보완) */
const BANNED = ['바보', '멍청', '섹스', '시발', '병신', '개새'];
export const isBannedNickname = (n) => BANNED.some((w) => n.includes(w));

export const NICKNAME_POOL_SIZE = NICK_PREFIXES.length * NICK_NOUNS.length; // 10,000

/** i 번째 조합 (0 ~ 9,999) */
export const nicknameAt = (i) => NICK_PREFIXES[Math.floor(i / NICK_NOUNS.length) % NICK_PREFIXES.length] + NICK_NOUNS[i % NICK_NOUNS.length];

/**
 * 쓰지 않은 닉네임 n개를 무작위로 고른다
 * @param {Set<string>} taken 이미 쓰는 닉네임
 */
export function suggestNicknames(n = 4, taken = new Set(), rnd = Math.random) {
  const out = new Set();
  for (let tries = 0; out.size < n && tries < n * 50; tries++) {
    const name = nicknameAt(Math.floor(rnd() * NICKNAME_POOL_SIZE));
    if (name.length <= 5 && !taken.has(name) && !isBannedNickname(name)) out.add(name);
  }
  return [...out];
}
